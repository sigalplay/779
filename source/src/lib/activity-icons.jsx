// The activity bank uses one calm, unified watercolor illustration per card.
// Keep the richer icon sets above for materials and individual steps.
export function activityHero(activityId) {
  const customHero = ACTIVITY_ICON_SETS[activityId]?.hero;
  if (customHero) return customHero;
  if (typeof activityId === "string" && /^seed-\d+$/.test(activityId)) {
    return `/icon-bank/activities/${activityId}.webp`;
  }
  return null;
}
