export function activityEmoji(a) {
  if (a?.emoji && a.emoji.trim()) return a.emoji;
  const text = `${a?.title ?? ""} ${a?.short_description ?? ""} ${a?.categories?.join(" ") ?? ""}`.toLowerCase();
  for (const [re, emoji] of MAP) if (re.test(text)) return emoji;
  return "✨";
}

