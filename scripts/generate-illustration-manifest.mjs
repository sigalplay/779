import { readFile, readdir, stat, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";

const root = path.resolve("public/icon-bank");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(entries.map((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  }));
  return nested.flat();
}

const imagePattern = /\.(?:avif|gif|jpe?g|png|svg|webp)$/i;
function dimensions(buffer, extension) {
  if (extension === ".png" && buffer.length >= 24) return [buffer.readUInt32BE(16), buffer.readUInt32BE(20)];
  if (extension === ".webp" && buffer.length >= 30) {
    const format = buffer.toString("ascii", 12, 16);
    if (format === "VP8X") return [1 + buffer.readUIntLE(24, 3), 1 + buffer.readUIntLE(27, 3)];
    if (format === "VP8 ") return [buffer.readUInt16LE(26) & 0x3fff, buffer.readUInt16LE(28) & 0x3fff];
    if (format === "VP8L" && buffer[20] === 0x2f) {
      const bits = buffer.readUInt32LE(21);
      return [1 + (bits & 0x3fff), 1 + ((bits >> 14) & 0x3fff)];
    }
  }
  return [null, null];
}

const files = await Promise.all((await walk(root)).filter((file) => imagePattern.test(file)).map(async (file) => {
  const buffer = await readFile(file);
  const [width, height] = dimensions(buffer, path.extname(file).toLowerCase());
  const info = await stat(file);
  return {
    path: `/${path.relative("public", file).split(path.sep).join("/")}`,
    width,
    height,
    bytes: info.size,
    hash: createHash("sha1").update(buffer).digest("hex").slice(0, 16),
  };
}));
files.sort((a, b) => a.path.localeCompare(b.path));

const output = `// Generated by scripts/generate-illustration-manifest.mjs.\nexport const ILLUSTRATION_FILES = ${JSON.stringify(files, null, 2)};\n`;
await writeFile("src/lib/illustration-files.generated.js", output);
console.log(`Indexed ${files.length} illustrations.`);
